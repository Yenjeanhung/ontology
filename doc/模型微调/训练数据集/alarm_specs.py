# 工具函数（生成端复用）
def rnd_reg():
    return f"B-{random.randint(1000, 9999)}"

def rnd_flight():
    return random.choice(AIRLINES) + str(random.randint(100, 8999))

def rnd_route():
    dep = random.choice(AIRPORTS)
    arr = random.choice([a for a in AIRPORTS if a != dep])
    return dep, arr

def rnd_hhmm():
    return f"{random.randint(0, 23):02d}:{random.choice(range(0, 60, 5)):02d}"

def rnd_area():
    city, _ = random.choice(AIRPORTS)
    return f"{city}{random.choice(AREAS)}约{random.choice([40, 60, 80, 120, 150, 200])}公里"

def ctx_generic(extra=None):
    (dc, di), (ac, ai) = rnd_route()
    ctx = {"fno": rnd_flight(), "reg": rnd_reg(), "actype": random.choice(AIRCRAFT),
           "dep_city": dc, "dep_iata": di, "arr_city": ac, "arr_iata": ai,
           "dep_t": rnd_hhmm(), "arr_t": rnd_hhmm(), "area": rnd_area(), "t": rnd_hhmm()}
    if extra:
        ctx.update(extra)
    return ctx

def route_card(ctx):
    return (f"{ctx['fno']}({ctx['reg']}/{ctx['actype']}){ctx['dep_city']}{ctx['dep_iata']}"
            f"{ctx['dep_t']}-{ctx['arr_t']}{ctx['arr_iata']}{ctx['arr_city']}")

